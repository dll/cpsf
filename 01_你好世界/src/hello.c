/*
 * ============================================================
 *  第1讲：表达式 —— 一切从这一行 printf 开始
 * ============================================================
 *  编译：gcc -Wall hello.c -o hello.exe
 *  运行：hello.exe
 *  输出：Hello, Plugin Framework!
 */

// ========== 第1行：头文件包含 ==========
//
// #include <stdio.h>
//
// 这行代码的意思是：「把 stdio.h 这个文件的内容，全部复制粘贴到这里」
//
// stdio 是什么？
//   s = standard（标准）
//   t = input（输入）
//   d = output（输出）
//   .h = header（头文件）
//
// 为什么要包含它？
//   因为我们要用 printf 函数，而 printf 的「声明」在 stdio.h 里面。
//   编译器需要先知道 printf 长什么样，才能检查我们用得对不对。
//
// 注意：stdio.h 里只有 printf 的「声明」（接口），没有「实现」（代码）。
//       printf 的真正代码在标准库文件（libc.a / libc.so）里。
//       这就是为什么我们需要「链接」这一步——后面会讲。
#include <stdio.h>
#include "console_utf8.h"

// ========== 第2行：主函数 ==========
//
// int main()
//
// main 函数是 C 程序的「入口」——程序从这里开始执行。
// 就像大楼的大门，你必须从这里进去。
//
// int 是什么意思？
//   表示 main 函数执行完之后，会返回一个整数。
//   这个整数用来告诉操作系统：程序是正常结束的，还是出了什么错。
//   return 0 表示正常结束，非0表示出错了。
int main()
{
    console_utf8_init();   /* 解决中文乱码：切换到 UTF-8 控制台 */
    // ========== 第3行：核心表达式 ==========
    //
    // printf("Hello, Plugin Framework!\n");
    //
    // 这是我们今天的主角：一个「函数调用表达式」
    //
    // 我们把它拆开来看看：
    //
    //   printf  → 函数名。这是标准库提供的一个函数，功能是打印文字。
    //             全称：print formatted（格式化打印）
    //
    //   ( ... ) → 参数列表。括号里的内容是传给函数的数据。
    //
    //   "Hello, Plugin Framework!\n"
    //           → 字符串常量。就是要打印的内容。
    //              双引号括起来的一串字符，叫字符串。
    //
    //   \n      → 转义字符。表示「换行」。
    //              就像打字机按一下回车键，光标移到下一行开头。
    //
    //   ;       → 分号。语句结束的标志。
    //              注意：分号不是表达式的一部分，它是语句的一部分。
    //              表达式 + 分号 = 表达式语句
    //
    // 所以这行代码做了什么？
    //   调用 printf 函数，把字符串 "Hello, Plugin Framework!\n" 传进去，
    //   printf 函数把这个字符串输出到屏幕上。
    //
    // 【关键问题】printf 的代码在哪里？
    //   答：不在我们的 hello.c 里！它在 C 标准库（C Standard Library）里。
    //   我们的代码只是「调用」它，就像你打电话叫外卖——
    //   你不用自己做饭，你只要打个电话（调用），
    //   外卖（printf的功能）就送到你面前了。
    //
    // 那 printf 的代码是怎么跑到我们的程序里的？
    //   答：通过「链接器」。
    //   链接器会从标准库文件（比如 libc.a）里找到 printf 的实现，
    //   把它和我们的代码拼在一起，变成一个完整的可执行文件。
    //   这就是「链接」的作用——下一帧详细讲！
    printf("Hello, Plugin Framework!\n");

    // ========== 第4行：返回 ==========
    //
    // return 0;
    //
    // 函数执行完毕，返回一个值。
    // 对于 main 函数，返回 0 表示程序正常结束。
    //
    // 这也是一个表达式——赋值表达式？不，这是 return 语句。
    // return 后面的 0 是表达式（常量表达式）。
    return 0;
}

/*
 * ============================================================
 *  附录：编译四阶段详解
 * ============================================================
 *
 * 从 hello.c 到 hello.exe，中间发生了什么？
 *
 * 阶段1：预处理（Preprocessing）
 *   输入：hello.c
 *   输出：hello.i
 *   命令：gcc -E hello.c -o hello.i
 *
 *   做什么？
 *     • 处理 #include 指令（把头文件内容复制进来）
 *     • 处理 #define 宏定义
 *     • 处理条件编译（#ifdef 等）
 *     • 删除注释
 *
 *   结果：还是 C 代码，但是所有「#开头的指令」都被处理掉了。
 *
 *
 * 阶段2：编译（Compilation）
 *   输入：hello.i
 *   输出：hello.s
 *   命令：gcc -S hello.c -o hello.s
 *
 *   做什么？
 *     • 把 C 代码翻译成汇编代码
 *     • 进行语法检查、优化
 *
 *   结果：汇编语言代码（人类能读懂的低级语言）。
 *
 *
 * 阶段3：汇编（Assembly）
 *   输入：hello.s
 *   输出：hello.o（目标文件）
 *   命令：gcc -c hello.c -o hello.o
 *
 *   做什么？
 *     • 把汇编代码翻译成机器码（0和1）
 *     • 生成目标文件（Object File）
 *
 *   结果：二进制文件，电脑能读懂，但还不能直接运行。
 *   为什么不能运行？因为 printf 的实现还不在里面！
 *   hello.o 里只说了「我要调用 printf」，但 printf 在哪？不知道。
 *
 *
 * 阶段4：链接（Linking）⭐ 最关键的一步！
 *   输入：hello.o + 标准库文件（libc.a / libc.dll）
 *   输出：hello.exe（可执行文件）
 *   命令：gcc hello.o -o hello.exe
 *
 *   做什么？
 *     • 解析「未定义的符号」——hello.o 里调用了 printf，但没有实现
 *     • 去标准库里找 printf 的实现
 *     • 把 printf 的代码「拼」到我们的程序里
 *     • 调整内存地址，让函数调用能正确找到目标
 *
 *   这就是「链接」名字的由来——
 *   把我们写的代码和库的代码「链接」在一起，
 *   形成一个完整的、能独立运行的程序。
 *
 *
 * 类比理解：
 *   你写了一篇作文（hello.c），但里面引用了一句名言（printf）。
 *   • 预处理：把引用的名言全文抄进来（展开头文件）
 *   • 编译：把作文翻译成盲文（汇编）
 *   • 汇编：把盲文刻成唱片（目标文件）
 *   • 链接：把名言的原版录音（printf实现）也加到唱片里
 *   最终：一张完整的、可以播放的唱片（可执行文件）
 *
 * ============================================================
 */
