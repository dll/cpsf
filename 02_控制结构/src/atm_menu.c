/*
 * ============================================================
 *  第2讲：控制结构 —— ATM 简易菜单
 *  从一行代码到一个完整的交互程序
 * ============================================================
 *
 *  三种控制结构：
 *    1. 顺序结构 —— 代码从上到下一行一行执行
 *    2. 分支结构 —— if / switch，根据条件走不同的路
 *    3. 循环结构 —— while / for，重复执行同一段代码
 *
 *  注意：本讲不使用函数，所有代码都在 main 里
 *        （为下一讲"函数封装"埋下伏笔——代码越来越长了）
 */

#include <stdio.h>

int main()
{
    // ========== 变量定义 ==========
    //
    // 我们需要一些"容器"来存放数据
    //   - balance：余额，初始1000元
    //   - choice：用户的菜单选择
    //   - amount：存款/取款金额
    //   - running：程序是否继续运行（1=运行，0=退出）
    //
    double balance = 1000.0;    // 账户余额
    int choice = 0;             // 用户选择
    double amount = 0.0;        // 交易金额
    int running = 1;            // 运行标志

    // ========== 顺序结构的演示 ==========
    //
    // 这几行 printf 是典型的「顺序结构」：
    // 从上到下，一行一行依次执行，不会跳，也不会回头。
    //
    printf("========================================\n");
    printf("       欢迎使用 CCIT ATM 系统\n");
    printf("========================================\n");
    printf("\n");

    // ========== 循环结构的演示 ==========
    //
    // while (running) 是一个循环：
    //   只要 running 的值是 1（真），就重复执行大括号里的代码
    //   当 running 变成 0（假），循环结束
    //
    // 为什么需要循环？
    //   用户做完一笔交易，应该回到菜单继续操作，
    //   而不是程序直接退出了。
    //
    while (running)
    {
        // ---- 第1步：显示菜单（顺序执行）----
        printf("\n-------- 主菜单 --------\n");
        printf("  1. 查询余额\n");
        printf("  2. 存款\n");
        printf("  3. 取款\n");
        printf("  4. 转账\n");
        printf("  0. 退出\n");
        printf("------------------------\n");
        printf("请输入您的选择：");

        // 读取用户输入
        scanf("%d", &choice);
        printf("\n");

        // ========== 分支结构的演示 ==========
        //
        // switch (choice) 根据 choice 的不同值，
        // 跳转到对应的 case 执行。
        //
        // 这就是「分支结构」——同一段代码，
        // 根据不同的条件，走不同的路径。
        //
        switch (choice)
        {
            // ---- 情况1：查询余额 ----
            case 1:
                printf("【查询余额】\n");
                printf("您当前的账户余额为：%.2f 元\n", balance);
                break;  // break 的意思：跳出 switch，不往下走了

            // ---- 情况2：存款 ----
            case 2:
                printf("【存款业务】\n");
                printf("请输入存款金额：");
                scanf("%lf", &amount);

                // if 也是分支结构
                if (amount > 0)
                {
                    balance = balance + amount;
                    printf("✅ 存款成功！存入 %.2f 元\n", amount);
                    printf("当前余额：%.2f 元\n", balance);
                }
                else
                {
                    printf("❌ 存款金额必须大于0！\n");
                }
                break;

            // ---- 情况3：取款 ----
            case 3:
                printf("【取款业务】\n");
                printf("请输入取款金额：");
                scanf("%lf", &amount);

                // 用 if-else 做条件判断
                if (amount <= 0)
                {
                    printf("❌ 取款金额必须大于0！\n");
                }
                else if (amount > balance)
                {
                    printf("❌ 余额不足！当前余额：%.2f 元\n", balance);
                }
                else
                {
                    balance = balance - amount;
                    printf("✅ 取款成功！取出 %.2f 元\n", amount);
                    printf("当前余额：%.2f 元\n", balance);
                }
                break;

            // ---- 情况4：转账 ----
            case 4:
                printf("【转账业务】\n");
                printf("请输入转账金额：");
                scanf("%lf", &amount);

                if (amount <= 0)
                {
                    printf("❌ 转账金额必须大于0！\n");
                }
                else if (amount > balance)
                {
                    printf("❌ 余额不足，无法转账！\n");
                }
                else
                {
                    int target_account = 0;
                    printf("请输入对方账号：");
                    scanf("%d", &target_account);
                    balance = balance - amount;
                    printf("✅ 转账成功！向账号 %d 转出 %.2f 元\n", target_account, amount);
                    printf("当前余额：%.2f 元\n", balance);
                }
                break;

            // ---- 情况0：退出 ----
            case 0:
                printf("感谢使用 CCIT ATM 系统，再见！\n");
                running = 0;    // 把 running 设为 0，while 循环就结束了
                break;

            // ---- 其他情况：输入错误 ----
            default:
                printf("❌ 无效的选择，请重新输入！\n");
                break;
        }
    }

    return 0;
}

