#include <stdio.h>
#include "menu.h"

/*
 * show_welcome 实现
 * 打印欢迎标题
 */
void show_welcome(void)
{
    printf("========================================\n");
    printf("       欢迎使用 CCIT ATM 系统\n");
    printf("========================================\n");
    printf("\n");
}

/*
 * show_menu 实现
 * 打印主菜单选项
 */
void show_menu(void)
{
    printf("\n-------- 主菜单 --------\n");
    printf("  1. 查询余额\n");
    printf("  2. 存款\n");
    printf("  3. 取款\n");
    printf("  4. 转账\n");
    printf("  0. 退出\n");
    printf("------------------------\n");
}

/*
 * read_choice 实现
 * 提示用户输入并读取选择
 */
int read_choice(void)
{
    int choice = 0;
    printf("请输入您的选择：");
    scanf("%d", &choice);
    printf("\n");
    return choice;
}
