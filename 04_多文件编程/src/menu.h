/*
 * ============================================================
 *  menu.h —— 菜单模块头文件（接口）
 * ============================================================
 *
 *  为什么把菜单单独拆成一个模块？
 *
 *  在第3讲里，show_welcome 和 show_menu 是两个函数，和存款、
 *  取款等业务函数混在同一个文件里。但"显示菜单"和"处理业务"
 *  是两个完全不同的职责：
 *
 *  - 菜单模块：负责和用户交互（显示菜单、读取选择）
 *  - 账户模块：负责业务逻辑（存款、取款、转账、查询）
 *
 *  这叫"单一职责"——每个模块只做一件事。
 *  菜单变了改 menu.c，业务变了改 account.c，互不影响。
 *
 *  第3讲还把"读取用户输入"写在 main 函数里，
 *  现在我们把它抽到 read_choice 函数里，让 main 更清爽。
 * ============================================================
 */

#ifndef MENU_H    /* 头文件保护 */
#define MENU_H

/*
 * show_welcome —— 显示欢迎界面
 * 打印 ATM 系统的欢迎标题
 */
void show_welcome(void);

/*
 * show_menu —— 显示主菜单
 * 打印各功能选项
 */
void show_menu(void);

/*
 * read_choice —— 读取用户选择
 *
 * 返回值：用户输入的菜单选项（1/2/3/4/0）
 *
 * 把"提示输入 + scanf"封装成一个函数，
 * main 函数就不用每次都写这两行了。
 */
int read_choice(void);

#endif /* MENU_H */
