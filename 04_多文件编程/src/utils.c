/*
 * ============================================================
 *  utils.c —— 工具模块源文件（实现）
 * ============================================================
 *
 *  这里是工具函数的具体实现。
 *
 *  其他文件只看 utils.h（接口），不需要看 utils.c（实现）。
 *  如果哪天我们改了 print_success 的输出格式，
 *  只改 utils.c 就行，其他文件不用重新理解。
 *
 *  这就是"接口与实现分离"的好处：
 *  调用者依赖接口（头文件），不依赖实现（源文件）。
 *  实现可以随时换，只要接口不变，调用者就不受影响。
 * ============================================================
 */

#include <stdio.h>
#include "utils.h"   /* 包含自己的头文件，让编译器检查声明和定义是否一致 */

/*
 * print_success 实现
 * 打印统一的成功格式：操作名 + 金额 + 余额
 */
void print_success(const char* op, double amount, double balance)
{
    printf("✅ 操作成功！%s %.2f 元\n", op, amount);
    printf("当前余额：%.2f 元\n", balance);
}

/*
 * print_error 实现
 * 打印统一的错误格式
 */
void print_error(const char* msg)
{
    printf("❌ %s\n", msg);
}
