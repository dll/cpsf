/*
 * ============================================================
 *  utils.h —— 工具模块头文件（接口）
 * ============================================================
 *
 *  为什么单独拆一个 utils 模块？
 *
 *  在第3讲的单文件版本里，print_success 和 print_error 是公共函数，
 *  存款、取款、转账都要调用它们。现在拆成多文件后，account.c 也需要
 *  调用这些函数——如果不单独拆出来，account.c 就得自己再写一遍，
 *  这就违背了"代码复用"的原则。
 *
 *  所以我们把"通用工具函数"放到 utils 模块，谁需要谁 include。
 *
 *  头文件里只放"声明"（函数原型），不放"定义"（函数体）。
 *  这就是"接口与实现分离"——头文件是接口，源文件是实现。
 *
 *  比喻：头文件是"菜单"，告诉你有什么菜；
 *        源文件是"厨房"，菜是在这里做的。
 *        顾客（其他文件）看菜单点菜，不用进厨房。
 * ============================================================
 */

#ifndef UTILS_H    /* 头文件保护：防止被重复包含 */
#define UTILS_H    /* 如果没定义过 UTILS_H，就定义它 */

/*
 * print_success —— 打印操作成功信息
 *
 * 参数：
 *   op      - 操作名称（如"存入"/"取出"/"转出"）
 *   amount  - 操作金额
 *   balance - 操作后的余额
 *
 * 注意：第3讲里 print_success 直接访问全局变量 g_balance，
 *       现在余额被藏在 account.c 里（static），外部看不到，
 *       所以改成通过参数传入余额——这降低了模块间的耦合。
 */
void print_success(const char* op, double amount, double balance);

/*
 * print_error —— 打印错误信息
 *
 * 参数：
 *   msg - 错误提示文字
 */
void print_error(const char* msg);

#endif /* UTILS_H */
