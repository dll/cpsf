/*
 * ============================================================
 *  第11讲：运行时加载
 *  plugin_api.h —— 插件契约：约定好的导出符号
 * ============================================================
 *
 *  【为什么需要"约定"？】
 *    运行时加载解决了一个大问题：程序可以在运行中加载任意动态库。
 *    但随之而来一个新问题——加载进来之后，怎么调用它？
 *
 *    动态库里可能有成百上千个函数，宿主程序并不知道哪个是"入口"。
 *    就像你去火车站接人，如果不知道对方长什么样、叫什么名字，
 *    出站口涌出一堆人，你根本认不出要接的那位。
 *
 *    解决办法：大家提前约好一个"接头暗号"——
 *      ★ 插件必须导出固定名字的符号，宿主才能按名字找到它。
 *
 *  【本讲的约定（最简版）】
 *    每一个插件动态库都必须导出下面两个符号：
 *
 *      plugin_name    —— 返回插件名字的字符串，例如 "存款插件"
 *                        函数签名：const char *plugin_name(void);
 *
 *      plugin_execute —— 执行插件功能，参数是操作金额
 *                        函数签名：int plugin_execute(double amount);
 *                        返回值：0 表示成功，非 0 表示失败
 *
 *    命名上故意加 plugin_ 前缀，避免和库内其他符号冲突；
 *    也方便宿主一眼看出"这两个是插件的约定入口"。
 *
 *  【宿主伪代码】
 *      h = dynlib_open("xxx_plugin.dll");
 *      const char *(*get_name)(void)   = dynlib_sym(h, "plugin_name");
 *      int (*exec)(double)             = dynlib_sym(h, "plugin_execute");
 *      printf("加载插件：%s\n", get_name());
 *      exec(500.0);
 *
 *  【这个约定的局限 —— 本讲留下的"新痛点"】
 *    约定只是"叫这个名字"而已，还是很弱：
 *      - 名字虽然统一了，但参数和返回值只是"口头约定"，
 *        不同插件如果想干别的事（转账要两个账户、查询不要金额），
 *        就没法塞进 plugin_execute(double) 这一个小口子里；
 *      - 宿主必须写死调用两个函数，一个插件想多提供几个能力，
 *        宿主就得写死更多符号名；
 *      - 没有办法携带"插件元数据"（版本、作者、图标……）。
 *
 *    一句话：这只是"插件"的雏形。
 *    真正的解法是把这些函数指针打包成一个结构体接口，
 *    让宿主只认"一个接口"，不认"一堆散装函数名"——
 *    这就是第12讲"接口抽象"要干的事。
 *
 *  【编译要点】
 *    插件必须用 C 语言编译（不要 C++），否则函数名会被 C++
 *    的"名字修饰"（name mangling）改成一长串，约定名就对不上了。
 *    如果非要用 C++ 写插件，必须给函数加 extern "C"。
 * ============================================================
 */

#ifndef PLUGIN_API_H
#define PLUGIN_API_H

/* ============================================================
 *  一、跨平台导出宏
 * ============================================================
 *
 *  【为什么要导出？】
 *    动态库里不是所有符号都对外可见。默认情况下，
 *    有些平台（尤其 Windows）不会自动把函数放进"可查询的符号表"，
 *    GetProcAddress 就查不到。必须显式声明"我要导出"。
 *
 *    Windows：__declspec(dllexport) 把函数标记为导出。
 *    Linux  ：默认所有符号都可见，用
 *             __attribute__((visibility("default"))) 明确一下，
 *             顺便配合 -fvisibility=hidden 时保证该函数不被隐藏。
 *
 *    对比第10讲 account.h 的导出宏：
 *      第10讲还有"导入"分支（dllimport），因为主程序要链接导入库；
 *      第11讲宿主是用 GetProcAddress 按名字取地址的，
 *      根本不需要"导入"这回事，所以只需要"导出"这一个宏。
 */
#ifdef _WIN32
    #define PLUGIN_API __declspec(dllexport)
#else
    #define PLUGIN_API __attribute__((visibility("default")))
#endif

/* ============================================================
 *  二、约定的符号名（"接头暗号"）
 * ============================================================
 *
 *  宿主扫描目录时，就是拿这两个字符串去 dynlib_sym 查。
 *  写成宏，避免各处手写字符串时打错字（"plugin_exectue"这种）。
 */
#define PLUGIN_SYM_NAME     "plugin_name"       /* 取插件名字 */
#define PLUGIN_SYM_EXECUTE  "plugin_execute"    /* 执行插件功能 */

/* ============================================================
 *  三、函数指针类型（宿主用它来接收 dlsym 的结果）
 * ============================================================
 *
 *  dlsym/GetProcAddress 返回的是"地址"，
 *  宿主必须把它转成"正确的函数指针类型"才能调用。
 *  这里把类型定义好，宿主直接强转即可，不必每次手写冗长声明。
 *
 *  【对比第5讲】这就是第5讲学的函数指针，
 *    只不过指向的函数不在本程序里，而在运行时加载进来的库里。
 */
typedef const char *(*plugin_name_fn)(void);            /* plugin_name */
typedef int         (*plugin_execute_fn)(double amount); /* plugin_execute */

#endif /* PLUGIN_API_H */
