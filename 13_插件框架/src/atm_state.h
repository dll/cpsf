/*
 * ============================================================
 *  第13讲：插件框架架构
 *  atm_state.h —— ATM 共享账户状态（业务数据）
 * ============================================================
 *
 *  【为什么单独抽一个模块？】
 *    四个插件（存款/取款/查询/转账）操作的是"同一个账户"。
 *    如果每个插件各自保存一份余额，就乱套了。
 *    把业务数据抽成独立模块，插件只依赖接口、不依赖实现，
 *    这正是第4讲"头文件分离接口与实现"的延续。
 *
 *  注意：这个模块和插件框架本身无关——框架管理的是"插件"，
 *        不关心插件内部在算什么业务。业务与框架彻底解耦。
 * ============================================================
 */

#ifndef ATM_STATE_H
#define ATM_STATE_H

/* 重置账户（初始余额、收款账户清零） */
void   atm_reset(double initial_balance);

/* 查询当前余额 */
double atm_get_balance(void);

/* 查询"转账收款方"累计收到的金额 */
double atm_get_target(void);

/* 存款：成功返回 0，金额非法返回 -1 */
int    atm_deposit(double amount);

/* 取款：成功 0，金额非法 -1，余额不足 -2 */
int    atm_withdraw(double amount);

/* 转账：成功 0，金额非法 -1，余额不足 -2 */
int    atm_transfer(double amount);

#endif /* ATM_STATE_H */
