def main():
    src = io.open(TARGET, encoding='utf-8').read()
    miss = []
    for old, new in PAIRS:
        if old not in src:
            miss.append(old)
            continue
        src = src.replace(old, new)
    io.open(TARGET, 'w', encoding='utf-8', newline='\n').write(src)
    print('已替换 %d/%d 处' % (len(PAIRS) - len(miss), len(PAIRS)))
    for m in miss:
        print('  [未命中] %s' % m[:60])
    return 1 if miss else 0


